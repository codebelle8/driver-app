-- =============================================================================
-- 配信の鍵を、会員が読めるようにする
-- =============================================================================
--
-- 何が起きていたか:
--   20260909000003 で、秘密鍵を隠すために列を絞って渡した。
--
--     grant select (public_key, subject) on public.push_settings to authenticated;
--
--   ところが、アプリは1行しかない表から
--
--     select public_key from push_settings where id = 1
--
--   と読む。**絞り込みに使う列にも SELECT 権限が要る。** id を渡して
--   いなかったため、読み取りそのものが 42501 で弾かれていた。
--   （PostgREST の助言も「表ごと渡せ」という粗いものだった）
--
--   結果、アプリ側は「配信の鍵がまだ無い」と判断し、通知の欄が
--   ずっと「ただいま準備中です」のままになる。
--
-- **手元では気づけなかった。**
--   検証用データベースには PostgREST が無く、権限の一覧を見ても
--   「public_key, subject が読める」と出るだけで正しく見えた。
--   本番へ当てて、会員の鍵で叩いて初めて分かった。
--   検査を足してある（tools/check-push-guard.mjs）。
--
-- 直し方:
--   絞り込みに使う id も渡す。private_key は渡さないままにする。
-- =============================================================================

grant select (id, public_key, subject) on public.push_settings to authenticated;
