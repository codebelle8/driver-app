-- =============================================================================
-- 役割に「調査員 (surveyor)」を追加する
-- =============================================================================
--
-- 背景:
--   当初は「少数の信頼できる管理者が運用する」前提で admin / editor の2段階と
--   していた。現地調査を担当するドライバー20名へアカウントを発行するにあたり、
--   実データを壊せない第3の役割が必要になった。
--
-- このファイルを単独にしている理由:
--   PostgreSQL は「列挙型へ追加した値」を同じトランザクション内で使えない。
--   ポリシー定義で 'surveyor' を参照するため、追加だけを別ファイルへ分ける。
--   （supabase db push は1ファイル=1トランザクションで適用する）
--
-- 役割の定義:
--   admin    … すべて。アカウント管理と操作履歴の閲覧を含む
--   editor   … 内容の全操作。公開・削除も行える。アカウント管理は不可
--   surveyor … 下書きの作成・編集のみ。公開・削除は不可
-- =============================================================================

alter type public.admin_role add value if not exists 'surveyor';
