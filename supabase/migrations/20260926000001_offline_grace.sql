-- =============================================================================
-- 圏外で使える日数
-- =============================================================================
--
-- **なぜ要るか**（ご指摘 2026-09-23）
--   圏外で開くと、ログインの鍵（1時間で切れる）を取り替えられず、入口へ
--   戻されていた。圏外ではログインもできないため、行き止まりになる。
--   アプリは、最後にサーバーで確かめた会員の控えで通すようにした
--   （app/src/lib/account.ts）。電波が戻ると確かめ直す。
--
-- **なぜ上限を設けるか**
--   停止した方・ほかの端末へ移った方も、圏外のままなら控えで使い続け
--   られてしまう。最後に確かめてから、この日数を過ぎたら「電波の届く場所で
--   開いてください」と出して止める。
--
-- **既定は30日**。毎日使う乗務員の方なら、そのあいだに必ず一度は電波の
--   ある場所で開くため、実際に当たることはまず無い。管理画面の
--   「サイト設定」で変えられる（1〜365日）。
--
-- アプリは電波のある場所で開くたびにこの値を読み、控えに入れておく。
-- 圏外ではサーバーに聞けないため、控えの値で判断する。
-- =============================================================================

alter table public.site_settings
  add column offline_grace_days smallint not null default 30
  check (offline_grace_days between 1 and 365);

-- -----------------------------------------------------------------------------
-- 権限
--
--   読むのは、表ごとに渡してある（会員は読める）。列を足しても読める。
--   書くのは列ごとに渡しているため、足す。書き換えられるのは管理者だけ
--   （行の決まり site_settings_write_admin）。
-- -----------------------------------------------------------------------------
grant update (offline_grace_days) on public.site_settings to authenticated;

notify pgrst, 'reload schema';
