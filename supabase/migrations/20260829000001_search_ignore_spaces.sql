-- =============================================================================
-- 検索で空白と記号を無視する
-- =============================================================================
-- 症状（2026-08-29 本番で実測）:
--   名前に空白が入っている施設は、空白なしで打つと引けない。
--
--     ハイアットセントリック銀座東京   ★見つからない
--     シャングリラホテル東京         ★見つからない
--     オークウッドプレミアム東京      ★見つからない
--
--   さらに、括弧を含む名前は「一覧に書いてあるとおり」打つと引けない。
--
--     トランクホテル CAT STREET(TRUNK)   ★見つからない
--     ハイアット ハウス(Hyatt House)      ★見つからない
--
-- 原因:
--   1. 空白をそのまま照合していた。打つ人によって入れたり入れなかったりする。
--   2. 括弧・カンマを、問い合わせ側では取り除き、登録側では残していた。
--      両側の変換が食い違っていたため、名前のとおり打つと一致しなかった。
--
--   3. 中黒（・）も同じ事情。「シャングリ・ラ」を打つ人はまず「シャングリラ」と打つ。
--
-- 対処:
--   登録側・問い合わせ側の双方で、空白（半角・全角）と ( ) , % _ ・ を落とす。
--   アプリ側の同じ処理は app/src/lib/search.ts にあり、こちらと対で直している。
--   片方だけ変えると一致しなくなるため、必ず両方を揃えること。
--
--   **項目ごとに変換してから、空白でつなぐ。**
--   先に全部つないでから空白を落とすと、項目の切れ目が消えて
--   「前の項目の末尾＋次の項目の先頭」という、どこにも書かれていない語ができる。
--   実際に「丸ノ内ホテル」で、名前の末尾「…丸の内」とよみの先頭「ほてる…」が
--   つながり、ホテルメトロポリタン丸の内にも当たっていた。
--   問い合わせ側は空白を落とすので、ここに残した空白は切れ目として確実に働く。
--
-- 影響:
--   「帝国 内幸町」のように語の間に空白を入れた検索は、以前も引けなかった
--   （1つの部分一致で照合しているため）。今回もその点は変わらない。
-- =============================================================================

create or replace function public.normalize_search_text(input text)
returns text
language sql
immutable
as $$
  select translate(
    lower(translate(
      coalesce(input, ''),
      'ァアィイゥウェエォオカガキギクグケゲコゴサザシジスズセゼソゾタダチヂッツヅテデトドナニヌネノハバパヒビピフブプヘベペホボポマミムメモャヤュユョヨラリルレロワヲンー',
      'ぁあぃいぅうぇえぉおかがきぎくぐけげこごさざしじすずせぜそぞただちぢっつづてでとどなにぬねのはばぱひびぴふぶぷへべぺほぼぽまみむめもゃやゅゆょよらりるれろわをんー'
    )),
    -- 半角空白・タブ・改行・復帰・全角空白・記号・中黒
    ' ' || chr(9) || chr(10) || chr(13) || '　' || '%_,()・',
    ''
  );
$$;

comment on function public.normalize_search_text(text) is
  '検索の照合用に文字を揃える。空白・記号・中黒は落とす。app/src/lib/search.ts と同一。';

-- -----------------------------------------------------------------------------
-- 照合用の文字列の組み立て方を変える。
--
-- 項目ごとに変換してから空白でつなぐ。別名も1つずつ変換する
-- （まとめてから変換すると別名同士の切れ目が消える）。
-- -----------------------------------------------------------------------------
create or replace function public.facilities_refresh_search_text()
returns trigger
language plpgsql
as $$
begin
  new.search_text := concat_ws(' ',
    public.normalize_search_text(new.name),
    public.normalize_search_text(new.name_kana),
    (
      select string_agg(public.normalize_search_text(a), ' ')
      from unnest(coalesce(new.aliases, '{}')) as a
    ),
    public.normalize_search_text(new.prefecture),
    public.normalize_search_text(new.city),
    public.normalize_search_text(new.address_line)
  );
  return new;
end;
$$;

-- -----------------------------------------------------------------------------
-- 既存の施設に、新しい規則で作り直した検索用の文字列を入れ直す。
--
-- search_text は before update のトリガが組み立てるため、
-- 行を更新すれば自動で作り直される。
-- 操作履歴には35件の更新として記録される。
-- -----------------------------------------------------------------------------
