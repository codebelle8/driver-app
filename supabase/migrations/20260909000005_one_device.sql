-- =============================================================================
-- 1つのアカウントは1台まで
-- =============================================================================
--
-- ご指示（2026-09-09）。設計案で「決めておくべきこと」に挙げていた
-- 「1つのアカウントで同時に使える端末数」が、1台に決まった。
--
-- **なぜ後勝ちにするか**
--   先に入っている端末を優先して、2台目を断る作りにもできる。
--   ただしそれだと、機種変更・紛失・故障のたびに入れなくなり、
--   こちらへ連絡して外してもらうまで使えない。走行前の車内で
--   起こると、その日は仕事にならない。
--
--   **新しく入った端末を通し、前の端末を落とす。** 乗り換えは自分で
--   済み、盗られた端末も入り直せば締め出せる。
--
-- **どう見分けるか**
--   端末ごとに1つの符号を作り、名簿に「いまの1台」として控える。
--   入り直すたびに上書きし、控えと違う端末は自分から出ていく。
--
--   Supabase 側の「他の端末からログアウト」も同時に呼ぶが、あちらは
--   手元の鍵が切れるまで（最大1時間）効かない。すぐ効かせるために、
--   こちらの控えと突き合わせる。
--
-- **符号そのものに意味は持たせない**
--   端末を特定できる値（広告IDなど）は使わない。その端末でこのアプリを
--   初めて開いたときに作る、ただのでたらめな文字列。消せば別の端末に
--   なるが、そのときは入り直していただくだけで済む。
-- =============================================================================

alter table public.driver_profiles
  add column device_id text;

/*
  会員自身が書き換える列。ログインのたびに、その端末の符号を入れる。

  **足す前に剥がす、の例外。** ここは列ごとの grant を「足す」のが正しい。
  update の列権限は重ねて持てる（20260908000003 で剥がしたのは、
  既定でぜんぶ渡っていたものを取り消すため）。
*/
grant update (device_id) on public.driver_profiles to authenticated;
