/**
 * ロゴが押されたことを、探す画面へ伝える。
 *
 * **なぜ経路だけでは足りないか**
 *   ロゴの行き先は探す画面だが、既にそこに居ると渡す先が同じで、
 *   何も起きない。絞り込んだ結果を見ている最中はとくにそうで、
 *   ロゴを押して何も起きないのは、押せないのと変わらない。
 *
 * **なぜ画面をまたぐ仕掛けが要るか**
 *   ロゴの置き場所は2つある。狭い画面では探す画面の頭、広い画面では
 *   左メニューの上。左メニューは画面の並びの外側にあり、探す画面の
 *   状態には手が届かない。押されたことだけを伝え、どうするかは
 *   受け取る側が決める。
 *
 * 覚えておくものは無い。押された瞬間に呼ぶだけ。
 */
type Listener = () => void;

const listeners = new Set<Listener>();

/** 受け取る側。戻り値を呼ぶと外れる（画面を離れるときに呼ぶ）。 */
export function onHomePressed(fn: Listener): () => void {
  listeners.add(fn);
  return () => {
    listeners.delete(fn);
  };
}

/** 押されたことを伝える。 */
export function homePressed(): void {
  // 呼ばれている最中に外れることがあるため、控えを取ってから回す
  for (const fn of [...listeners]) fn();
}
