/**
 * 画面幅ごとの作り分け。
 *
 * **なぜ要るか**
 *   PWA にしたことで、同じ画面が iPhone でも 27インチの外部画面でも開く。
 *   スマホ用の1枚を引き伸ばすと、1920px の画面でカード1枚が868px幅になり、
 *   中身は左端に寄ったまま、下半分が真っ白という見た目になっていた。
 *
 * **誰が PC で開くか**
 *   乗務員の方はスマホで、走行前に1件だけ調べる。
 *   PC で開くのは事務所側で、一覧を眺めて突き合わせる使い方になる。
 *   広い画面では「一度に見渡せること」を優先する。
 *
 * **区切りの決め方**
 *   端末の種類では分けない。同じ iPad でも横向きと縦向きで使える幅が違い、
 *   PC でも窓を半分にすればスマホと同じ幅になる。**そのときの幅だけ**で決める。
 *
 *     〜767      スマホ。1段組み。下タブ。
 *     768〜1023  PC の骨格（左の縦メニュー）。中身は縦積み。
 *     1024〜1199 一覧と地図を左右に並べる。
 *     1200〜     カテゴリの札を3列にする。
 */
import { useWindowDimensions } from 'react-native';

/**
 * PC の骨格に切り替える幅。
 *
 * 左の縦メニューを出し、下タブを消す。
 *
 * 以前は 1024 にしていたが、768〜1023 の画面（iPad の縦、PC の窓を
 * 半分にしたとき）でスマホの見た目のままだった。左メニューは
 * 256px で、768px でも本文に 512px 残る。一覧を1列で出すには足りる。
 */
export const WIDE = 768;

/**
 * 一覧と地図を左右に並べる幅。
 *
 * 骨格とは分けている。施設の画面の文章の列は 520px 固定で、
 * 768px から左メニュー 256px を引くと 512px しか残らない。
 * 文章の列だけで幅を使い切り、地図の置き場所が無くなる。
 */
export const SPLIT = 1024;

/**
 * カテゴリの札を3列にできる幅。
 *
 * 1024px では左メニューと余白を引くと本文が672pxしかなく、3列だと
 * 1枚が208px。「オフィスビル」が折り返し、説明も切れていた。
 * この幅を下回るあいだは2列にする。
 */
export const THREE_UP = 1200;

/**
 * 中身の最大幅。
 *
 * 本文の1行が長くなりすぎると、目が行末から次の行頭へ戻れなくなる。
 * 日本語で読みやすいのは1行40字前後で、この幅がおよその上限にあたる。
 * 左右分割の画面はこれに縛られない（地図は広いほうがよい）。
 */
export const CONTENT_MAX = 1120;

export interface Layout {
  width: number;
  height: number;
  /** 768px 以上。左メニューを出し、下タブを消す */
  isWide: boolean;
  /** 1024px 以上。一覧と地図を左右に並べる */
  isSplit: boolean;
  /** 1200px 以上。カテゴリの札を3列にできる */
  isThreeUp: boolean;
}

export function useLayout(): Layout {
  const { width, height } = useWindowDimensions();
  return {
    width,
    height,
    isWide: width >= WIDE,
    isSplit: width >= SPLIT,
    isThreeUp: width >= THREE_UP,
  };
}
