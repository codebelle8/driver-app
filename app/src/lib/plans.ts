/**
 * 料金の案内。
 *
 * **金額をここ1か所に置く**
 *   データベースにも表を作れるが、金額が変わるときは画面の但し書きも
 *   一緒に変わる（「2か月ぶんお得」など）。別々に持つと片方だけが古くなる。
 *   数が少ないので、ここに置いて画面から引く。
 *
 *   **画面の側で刻みごとに書き分けないこと。** 以前は「月額か年額か」を
 *   その場で判じていたため、刻みを増やすときに画面を1つずつ直す形に
 *   なっていた。名前も金額も、この表から引く。
 *
 * **まだ支払いは受け取れない**
 *   決済の仕組みは未定で、支払者がドライバー個人か事業者かも未回答
 *   （docs/12-phase2-design.md 2-1）。いまできるのは「どちらをご希望か」を
 *   伺って控えることまで。**使えるかどうかは status が決める。**
 *   選んだだけでは有料の扱いにならない。
 */

/**
 * 刻みの名前。
 *
 * **3か月（quarterly）・6か月（half）は、取り扱いを終えた**（2026-10-04）。
 * 名前だけは残している。以前に選んだ方の記録がデータベースに残っており、
 * 名前が引けないと「何を選んでいたか」が画面に出せない。
 * 申し込みの選択肢には出さない（下の PLANS に無い）。
 */
export type PlanId = 'monthly' | 'quarterly' | 'half' | 'yearly';

export interface Plan {
  id: PlanId;
  /** 税込の金額（円） */
  yen: number;
  /** 何か月ぶんか */
  months: number;
}

/*
  金額は発注元のご希望のとおり（2026-10-04）。

    1か月               600円
    12か月（一括払い）  5,000円

  以前は 1か月 4,000円／3か月 11,000円／6か月 21,000円／1年 40,000円 の
  4つだった（2026-09-14）。3か月・6か月は無くなった。
  1か月は「600円程度」とのご回答で、確定ではない。変わったらここを直す。

  **並びは短い順。** 長いほうから並べると、いちばん高い金額が最初に
  目に入る。

  **「1か月あたり◯円」は出さない。** ご指示により、金額そのものだけを
  出す（2026-09-09）。
*/
export const PLANS: readonly Plan[] = [
  { id: 'monthly', yen: 600, months: 1 },
  { id: 'yearly', yen: 5000, months: 12 },
];

/**
 * いま申し込める刻み。取り扱いを終えた刻み（3か月・6か月）と未選択は null。
 *
 * **取り扱いを終えた刻みを、別の刻みに読み替えない。** 以前は見つからない
 * ときに先頭（1か月）を返していた。6か月を選んでいた方に「1か月 600円」の
 * 振込先を出すと、選んでいない金額を振り込ませることになる。
 */
export const offeredPlan = (id: PlanId | null): Plan | null =>
  PLANS.find((p) => p.id === id) ?? null;

/**
 * 3桁ごとに区切る。
 *
 * toLocaleString に頼らない。端末の言語設定によっては区切りが変わり、
 * 40,000 が 40.000 になる。金額の見間違いは起こしたくない。
 */
export function yen(n: number): string {
  const s = String(Math.round(n));
  return s.replace(/\B(?=(\d{3})+(?!\d))/g, ',');
}

/*
  「1か月あたり◯円」「◯か月ぶんお得」を添えていたが、ご指示により外した。
  金額そのものだけを出す。
*/
